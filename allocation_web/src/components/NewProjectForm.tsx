import React, { useState, useEffect } from 'react';
import './NewProjectForm.css';
import { enhancedTempStorage } from '../utils/tempStorage';
import type { TempProjectFormData } from '../utils/tempStorage';
import { createProject, updateProject, deleteProject as apiDeleteProject, getProjectById } from '../api/projectApi';
import DeleteConfirmModal from './DeleteConfirmModal';

interface NewProjectFormProps {
  onBack: () => void;
  existingProjectId?: number;
  draftProjectId?: number;
  onProjectCreated?: (projectData: any) => void;
}

const NewProjectForm: React.FC<NewProjectFormProps> = ({ onBack, existingProjectId, draftProjectId, onProjectCreated }) => {
  const [formData, setFormData] = useState<TempProjectFormData>({
    projectName: '',
    projectId: '',
    courseCode: '',
    semester: '',
    maxGroups: '',
    projectType: '',
    deadline: '',
    description: '',
    client: '',
    deliverables: '',
    specificSkills: '',
    generalFields: '',
    resourcesProvided: '',
    tags: [],
    startTime: '',
    finishTime: ''
  });

  const [selectedTags, setSelectedTags] = useState<string[]>([]);
  
  // modal state management
  const [showDeleteConfirm, setShowDeleteConfirm] = useState(false);
  const [showSuccessMessage, setShowSuccessMessage] = useState(false);
  const [successMessage, setSuccessMessage] = useState('');
  const [showDeleteErrorModal, setShowDeleteErrorModal] = useState(false);
  const [deleteErrorMessage, setDeleteErrorMessage] = useState('');
  const [isDeleting, setIsDeleting] = useState(false);
  const [fetchBanner, setFetchBanner] = useState<{ type: 'success' | 'error' | 'notice'; message: string } | null>(null);
  
  // validation state
  const [validationErrors, setValidationErrors] = useState<{[key: string]: string}>({});
  
  // submission state
  const [isSubmitting, setIsSubmitting] = useState(false);

  const availableTags = [
    'Algorithms',
    'Database',
    'Graph',
    'Data Science/Analytics/Visualisation',
    'Machine Learning',
    'Deep Learning',
    'Image Processing/Segmentation',
    'Web Development',
    'Mobile APP',
    'Cloud Computing (AWS/AZURE/GCP)',
    'CNN/DNN/GAN/GNN',
    'VR/AR/Unity 3D/Unreal',
    'UI/UX',
    'Business Analysis/Risk Analysis',
    'Bioinformatics',
    'Software Development',
    'Artificial Intelligence',
    'Information Systems',
    'Security/Networks',
    'Computer vision',
    'Biological imaging',
    'Medical imaging',
    'industrial imaging',
    'NLP',
    'Robotics'
  ];

  // check if in edit mode
  const isEditMode = !!existingProjectId;

  // time tracking: record start time
  useEffect(() => {
    if (!formData.startTime) {
      const now = new Date();
      const formattedTime = `${now.getFullYear()}/${now.getMonth() + 1}/${now.getDate()} ${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}:${now.getSeconds().toString().padStart(2, '0')}`;
      setFormData(prev => ({ ...prev, startTime: formattedTime }));
      console.log('Setting project start time:', formattedTime);
    }
  }, []);

  // ensure start time is set
  useEffect(() => {
    if (!formData.startTime) {
      const now = new Date();
      const formattedTime = `${now.getFullYear()}/${now.getMonth() + 1}/${now.getDate()} ${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}:${now.getSeconds().toString().padStart(2, '0')}`;
      setFormData(prev => ({ ...prev, startTime: formattedTime }));
      console.log('Fallback project start time setting:', formattedTime);
    }
  }, [formData.startTime]);

  // auto-generate projectId for new projects
  useEffect(() => {
    if (!isEditMode && !formData.projectId) {
      // For draft projects, use the projectId from the route
      if (draftProjectId) {
        const draftIdStr = `P${draftProjectId.toString().padStart(2, '0')}`;
        setFormData(prev => ({ ...prev, projectId: draftIdStr }));
        console.log('Using draft project ID:', draftIdStr);
      } else {
        // Generate a unique project ID in P## format for completely new projects
        const generateProjectId = () => {
          // Get existing projects from localStorage to avoid conflicts
          const savedProjects = localStorage.getItem('createdProjects');
          const existingProjects = savedProjects ? JSON.parse(savedProjects) : [];
          
          const existingIds = existingProjects.map((p: any) => {
            const match = String(p.id).match(/^P(\d+)$/);
            return match ? parseInt(match[1], 10) : 0;
          });
          const maxId = Math.max(0, ...existingIds);
          const nextId = maxId + 1;
          return `P${nextId.toString().padStart(2, '0')}`;
        };
        
        const autoGeneratedId = generateProjectId();
        setFormData(prev => ({ ...prev, projectId: autoGeneratedId }));
        console.log('Auto-generated project ID:', autoGeneratedId);
      }
    }
  }, [isEditMode, formData.projectId, draftProjectId]);

  // load data from unified pseudo file system
  useEffect(() => {
    if (isEditMode && existingProjectId) {
      // completed edit: fetch latest from backend first, then fallback to file storage
      (async () => {
        try {
          const data = await getProjectById(existingProjectId);
          const mapped: any = {
            projectName: data.projectName || '',
            projectId: (data as any).projectId || '',
            maxGroups: String(data.maxGroups ?? ''),
            client: data.client || '',
            description: data.description || '',
            deliverables: data.deliverables || '',
            specificSkills: data.specificSkills || '',
            resourcesProvided: data.resourcesProvided || '',
            tags: Array.isArray(data.tags) ? data.tags : [],
            startTime: data.startTime || '',
            finishTime: data.finishTime || ''
          };
          setFormData(mapped);
          setSelectedTags(mapped.tags || []);
          setFetchBanner({ type: 'success', message: 'Loaded latest project from backend.' });
          // sync caches
          enhancedTempStorage.saveProjectToFile(existingProjectId, mapped);
          try {
            const savedRaw = localStorage.getItem('createdProjects');
            if (savedRaw) {
              const saved = JSON.parse(savedRaw);
              const updated = saved.map((p: any) => (
                p.id === existingProjectId
                  ? {
                      ...p,
                      name: mapped.projectName || p.name,
                      maxGroups: mapped.maxGroups || p.maxGroups,
                      status: 'completed',
                      formData: {
                        ...(p.formData || {}),
                        ...mapped
                      }
                    }
                  : p
              ));
              localStorage.setItem('createdProjects', JSON.stringify(updated));
              window.dispatchEvent(new StorageEvent('storage', { key: 'createdProjects', newValue: JSON.stringify(updated) }));
            }
          } catch (_) {}
        } catch (e: any) {
          // fallback to file cache if backend fails
          const fileData = enhancedTempStorage.loadProjectFromFile(existingProjectId);
          if (fileData) {
            setFormData(fileData);
            setSelectedTags(Array.isArray(fileData.tags) ? fileData.tags : []);
            console.log(`📂 Loaded project data from file system: ${existingProjectId}`);
            setFetchBanner({ type: 'error', message: `Backend fetch failed (${e?.message || 'Unknown error'}). Showing local data snapshot. Updating may overwrite your local data.` });
          }
        }
      })();
    } else {
      // new mode: load draft data from pseudo file system
      const savedData = draftProjectId
        ? enhancedTempStorage.loadProjectFromFile(draftProjectId)
        : enhancedTempStorage.loadDraftProject();
      if (savedData && Object.keys(savedData).length > 0) {
        // filter out undefined values, only keep meaningful strings
        const filteredData = Object.fromEntries(
          Object.entries(savedData).filter(([, value]) => 
            value !== undefined && value !== null && value !== ''
          )
        );
        setFormData(prev => ({ ...prev, ...filteredData }));
        setSelectedTags(Array.isArray(filteredData.tags) ? filteredData.tags : []);
        console.log('📂 Loaded draft project data from file system');
      } else {
        // first time entering page, record start time
        const now = new Date();
        const formattedTime = `${now.getFullYear()}/${now.getMonth() + 1}/${now.getDate()} ${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}:${now.getSeconds().toString().padStart(2, '0')}`;
        setFormData(prev => ({ ...prev, startTime: formattedTime }));
        console.log('Setting initial project start time:', formattedTime);
      }
      
      // Ensure projectId is set for draft projects
      if (draftProjectId && !formData.projectId) {
        const draftIdStr = `P${draftProjectId.toString().padStart(2, '0')}`;
        setFormData(prev => ({ ...prev, projectId: draftIdStr }));
        console.log('Set projectId for draft project:', draftIdStr);
      }
    }
  }, [isEditMode, existingProjectId]);

  // automatically save data to temporary storage (with debounce) - only in new mode
  useEffect(() => {
    if (!isEditMode) {
      const timeoutId = setTimeout(() => {
        const dataToSave = { ...formData, tags: selectedTags };
        try {
          if (draftProjectId) {
            enhancedTempStorage.saveProjectToFile(draftProjectId, dataToSave);
          } else {
            enhancedTempStorage.saveDraftProject(dataToSave);
          }
        } catch (error) {
          console.error('❌ Failed to save project draft data:', error);
        }
      }, 500);

      return () => clearTimeout(timeoutId);
    }
  }, [formData, selectedTags, isEditMode]);

  // in new mode, live-sync draft data to outer project card for display
  useEffect(() => {
    if (!isEditMode && draftProjectId) {
      const timeoutId = setTimeout(() => {
        const dataToSave = { ...formData, tags: selectedTags } as any;
        const savedProjectsRaw = localStorage.getItem('createdProjects');
        if (savedProjectsRaw) {
          try {
            const projects = JSON.parse(savedProjectsRaw);
            const updated = projects.map((p: any) => (
              p.id === `P${draftProjectId.toString().padStart(2, '0')}`
                ? {
                    ...p,
                    name: dataToSave.projectName || p.name,
                    maxGroups: dataToSave.maxGroups ? parseInt(dataToSave.maxGroups) : (p.maxGroups || null),
                    formData: {
                      ...(p.formData || {}),
                      ...dataToSave
                    },
                    lastModified: new Date().toISOString()
                  }
                : p
            ));
            localStorage.setItem('createdProjects', JSON.stringify(updated));
            // notify listeners (same-tab)
            window.dispatchEvent(new StorageEvent('storage', {
              key: 'createdProjects',
              newValue: JSON.stringify(updated)
            }));
          } catch (e) {
            console.warn('Failed to sync draft card:', (e as any)?.message);
          }
        }
      }, 400);
      return () => clearTimeout(timeoutId);
    }
  }, [formData, selectedTags, isEditMode, draftProjectId]);

  // in edit mode, real-time sync data to outer card
  useEffect(() => {
    if (isEditMode && existingProjectId) {
      const timeoutId = setTimeout(() => {
        const dataToSave = { ...formData, tags: selectedTags };
        
        // update file system structure
        enhancedTempStorage.saveProjectToFile(existingProjectId, dataToSave);
        
        // sync update outer project card
        const savedProjects = localStorage.getItem('createdProjects');
        if (savedProjects) {
          const projects = JSON.parse(savedProjects);
          const updatedProjects = projects.map((p: any) => 
            p.id === existingProjectId 
              ? { 
                  ...p, 
                  name: dataToSave.projectName || p.name,
                  formData: dataToSave,
                  lastModified: new Date().toISOString()
                }
              : p
          );
          localStorage.setItem('createdProjects', JSON.stringify(updatedProjects));
          
          // trigger storage event, notify other components to update
          window.dispatchEvent(new StorageEvent('storage', {
            key: 'createdProjects',
            newValue: JSON.stringify(updatedProjects)
          }));
        }
      }, 500);

      return () => clearTimeout(timeoutId);
    }
  }, [formData, selectedTags, isEditMode, existingProjectId]);

  const handleInputChange = (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>) => {
    const { name, value } = e.target;
    // console.log('📝 Project input change:', name, value);
    
    setFormData(prev => {
      const newData = { ...prev, [name]: value };
      // console.log('🔄 Project form data updated:', newData);
      return newData;
    });
  };

  const handleTagToggle = (tag: string) => {
    // console.log('🎯 Project tag toggle:', tag);
    setSelectedTags(prev => {
      const newTags = prev.includes(tag) 
        ? prev.filter(t => t !== tag)
        : [...prev, tag];
      // console.log('🔄 Project tags updated:', newTags);
      return newTags;
    });
  };


  // Validation function
  const validateForm = () => {
    console.log('🔍 validateProject called with formData:', formData);
    console.log('🔍 selectedTags:', selectedTags);
    const errors: {[key: string]: string} = {};

    // 1. Project Name validation
    const projectNameStr = String(formData.projectName ?? '').trim();
    if (!projectNameStr) {
      errors.projectName = 'Project Name is required';
      console.log('❌ Project Name is empty');
    }

    // 2. Project ID validation
    const projectIdStr = String(formData.projectId ?? '').trim();
    if (!projectIdStr) {
      errors.projectId = 'Project ID is required';
      console.log('❌ Project ID is empty');
    } else if (!/^P\d{2}$/.test(projectIdStr)) {
      errors.projectId = 'Project ID must be in format P followed by 2 digits (e.g., P01, P02, P10)';
      console.log('❌ Project ID format is invalid:', projectIdStr);
    }

    // 3. Max Groups validation - must be pure number
    const maxGroupsStr = String(formData.maxGroups ?? '').trim();
    if (!maxGroupsStr) {
      errors.maxGroups = 'Number of groups is required';
      console.log('❌ Max Groups is empty');
    } else if (!/^\d+$/.test(maxGroupsStr)) {
      errors.maxGroups = 'Number of groups must be a valid number';
      console.log('❌ Max Groups is not a valid number:', maxGroupsStr);
    } else {
      const numGroups = parseInt(maxGroupsStr);
      if (numGroups < 1) {
        errors.maxGroups = 'Number of groups must be at least 1';
        console.log('❌ Max Groups is less than 1:', numGroups);
      }
    }

    // 4. Client validation
    const clientStr = String(formData.client ?? '').trim();
    if (!clientStr) {
      errors.client = 'Client is required';
      console.log('❌ Client is empty');
    }

    // 5. Description validation
    const descriptionStr = String(formData.description ?? '').trim();
    if (!descriptionStr) {
      errors.description = 'Project Description is required';
      console.log('❌ Description is empty');
    }

    // 6. Deliverables validation
    const deliverablesStr = String(formData.deliverables ?? '').trim();
    if (!deliverablesStr) {
      errors.deliverables = 'Expected Outcomes/Deliverables is required';
      console.log('❌ Deliverables is empty');
    }

    // 7. Specific Skills validation
    const specificSkillsStr = String(formData.specificSkills ?? '').trim();
    if (!specificSkillsStr) {
      errors.specificSkills = 'Specific Required Knowledge/Skills is required';
      console.log('❌ Specific Skills is empty');
    }

    // 7. General Fields validation - at least one tag must be selected
    if (!selectedTags || selectedTags.length === 0) {
      errors.generalFields = 'At least one related field/discipline must be selected';
      console.log('❌ No general fields selected');
    }

    // 8. Resources Provided validation
    const resourcesProvidedStr = String(formData.resourcesProvided ?? '').trim();
    if (!resourcesProvidedStr) {
      errors.resourcesProvided = 'Resources Provided by Client is required';
      console.log('❌ Resources Provided is empty');
    }

    console.log('🔍 All validation errors found:', errors);
    return errors;
  };

  // Focus on error field
  const focusErrorField = (fieldName: string) => {
    if (fieldName === 'generalFields') {
      // Scroll to General Fields section
      const generalFieldsSection = document.querySelector('.tags-container');
      if (generalFieldsSection) {
        generalFieldsSection.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }
    } else {
      const element = document.getElementById(fieldName);
      if (element) {
        element.focus();
        element.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    
    console.log('🔍 DEBUG: Submit button clicked!');
    
    // ✅ First perform form validation
    const errors = validateForm();
    if (Object.keys(errors).length > 0) {
      setValidationErrors(errors);
      
      // Find first error field in priority order
      const fieldPriority = [
        'projectName',
        'projectId', 
        'maxGroups',
        'client',
        'description',
        'deliverables',
        'specificSkills',
        'generalFields',
        'resourcesProvided'
      ];
      
      const firstErrorField = fieldPriority.find(field => errors[field]) || Object.keys(errors)[0];
      console.log('🎯 First error field:', firstErrorField, 'Error:', errors[firstErrorField]);
      
      setTimeout(() => {
        focusErrorField(firstErrorField);
      }, 100);
      
      return; // Prevent submission
    }
    
    // Clear previous validation errors
    setValidationErrors({});
    
    // Set submission state
    setIsSubmitting(true);
    
    // record finish time
    const now = new Date();
    const finishTime = `${now.getFullYear()}/${now.getMonth() + 1}/${now.getDate()} ${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}:${now.getSeconds().toString().padStart(2, '0')}`;
    
    const finalData = {
      ...formData,
      tags: selectedTags,
      finishTime
    };
    
    // 📤 Print final data structure to be sent to backend
    console.log('📤 Sending project data (finalData):', finalData);
    console.log('📑 Payload fields:', Object.keys(finalData));
    
    try {
      // Call create or update based on mode
      const apiResponse = isEditMode && existingProjectId
        ? await updateProject(existingProjectId, finalData)
        : await createProject(finalData);
      
      // 📥 Print response content received from backend
      console.log('📥 Received API response:', apiResponse);
      
      // Save to local storage
      if (isEditMode && existingProjectId) {
        // Edit mode: update file system
        enhancedTempStorage.saveProjectToFile(existingProjectId, finalData);
        console.log(`Project data updated in file system: ${existingProjectId}`);
      } else {
        // New mode: clear draft cache
        // Sync: if cache exists by draft card ID, migrate to backend returned projectID
        const createdId = (apiResponse as any)?.projectID;
        if (draftProjectId && typeof createdId === 'number') {
          const draftData = enhancedTempStorage.loadProjectFromFile(draftProjectId);
          if (draftData) {
            enhancedTempStorage.saveProjectToFile(createdId, { ...draftData, ...finalData });
          } else {
            enhancedTempStorage.saveProjectToFile(createdId, finalData);
          }
          enhancedTempStorage.deleteProjectFile(draftProjectId);
        } else {
          enhancedTempStorage.clearDraftProject();
        }
      }
      
      // Call callback function
      if (onProjectCreated) {
        onProjectCreated({
          ...finalData,
          isComplete: true,
          projectID: (apiResponse as any)?.projectID
        });
      }
      
      // Show success message
      setSuccessMessage(isEditMode ? 'Project updated successfully!' : 'Project created successfully!');
      setShowSuccessMessage(true);
      
      // Auto-close and return after 2 seconds
      setTimeout(() => {
        setShowSuccessMessage(false);
        onBack();
      }, 2000);
      
    } catch (error: any) {
      console.error('❌ Failed to create project:', error);
      
      let errorMessage = 'Failed to create project. Please try again.';
      
      if (error.message) {
        const httpMatch = error.message.match(/HTTP (\d+):\s*(.+)/);
        if (httpMatch) {
          const statusCode = httpMatch[1];
          const statusText = httpMatch[2];
          errorMessage = `HTTP ${statusCode}\n${statusText}`;
        } else {
          if (error.message.includes('fetch')) {
            errorMessage = ` Network Error\nCannot connect to server.\n\nPlease check if the backend is running.`;
          } else if (error.message.includes('timeout')) {
            errorMessage = ` Timeout Error\nRequest timed out.\n\nPlease try again.`;
          } else {
            errorMessage = ` Error\n${error.message}`;
          }
        }
      }
      
      setSuccessMessage(errorMessage);
      setShowSuccessMessage(true);
      
      setTimeout(() => {
        setShowSuccessMessage(false);
      }, 3000);
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleBack = () => {
    // if there is existing project data, save to file system structure
    if (isEditMode && existingProjectId) {
      const currentData = {
        ...formData,
        tags: selectedTags
      };
      
      // save to file system structure
      enhancedTempStorage.saveProjectToFile(existingProjectId, currentData);
      console.log(`💾 Project data saved to file system before going back`);
    } else {
      // in new mode, persist draft on back instead of clearing
      const currentDraft = { ...formData, tags: selectedTags };
      try {
        if (draftProjectId) {
          enhancedTempStorage.saveProjectToFile(draftProjectId, currentDraft);
        } else {
          enhancedTempStorage.saveDraftProject(currentDraft);
        }
        console.log('💾 Draft project saved before going back');
      } catch (e) {
        console.warn('Failed to save draft before back:', (e as any)?.message);
      }
    }
    
    // return to previous page
    onBack();
  };

  const handleDeleteProject = () => {
    if (isEditMode) {
      setShowDeleteConfirm(true);
    } else {
      // In new mode, treat as cancel but persist draft
      const currentDraft = { ...formData, tags: selectedTags };
      try {
        if (draftProjectId) {
          enhancedTempStorage.saveProjectToFile(draftProjectId, currentDraft);
        } else {
          enhancedTempStorage.saveDraftProject(currentDraft);
        }
        console.log('💾 Draft project saved on cancel');
      } catch (e) {
        console.warn('Failed to save draft on cancel:', (e as any)?.message);
      }
      onBack();
    }
  };

  // confirm delete project
  const confirmDeleteProject = async () => {
    setIsDeleting(true);
    if (isEditMode && existingProjectId) {
      // In edit mode (completed project), call backend delete first and only remove locally on success
      try {
        await apiDeleteProject(existingProjectId);
        const savedProjects = localStorage.getItem('createdProjects');
        if (savedProjects) {
          const projects = JSON.parse(savedProjects);
          const updatedProjects = projects.filter((p: any) => p.id !== existingProjectId);
          localStorage.setItem('createdProjects', JSON.stringify(updatedProjects));
        }
        enhancedTempStorage.deleteProjectFile(existingProjectId);
        console.log(`🗑️ Project file deleted from file system: ${existingProjectId}`);
        setSuccessMessage('Project deleted successfully!');
        setShowSuccessMessage(true);
        setTimeout(() => {
          setShowSuccessMessage(false);
          onBack();
        }, 500);
      } catch (err: any) {
        // Check if it's a 404/not found error - if so, delete locally since backend doesn't have it
        if (err?.message?.includes('404') || err?.message?.includes('not found') || err?.message?.includes('Not Found')) {
          console.log('Project not found in backend, proceeding with local deletion');
          const savedProjects = localStorage.getItem('createdProjects');
          if (savedProjects) {
            const projects = JSON.parse(savedProjects);
            const updatedProjects = projects.filter((p: any) => p.id !== existingProjectId);
            localStorage.setItem('createdProjects', JSON.stringify(updatedProjects));
          }
          enhancedTempStorage.deleteProjectFile(existingProjectId);
          console.log(`🗑️ Project file deleted from file system: ${existingProjectId}`);
          setSuccessMessage('Project deleted successfully!');
          setShowSuccessMessage(true);
          setTimeout(() => {
            setShowSuccessMessage(false);
            onBack();
          }, 500);
        } else {
          console.warn('Backend delete failed; preserving local copy:', err?.message);
          setDeleteErrorMessage(err?.message || 'Failed to delete project from backend');
          setShowDeleteErrorModal(true);
          // keep local storage and close dialog only
        }
      }
    }
    setShowDeleteConfirm(false);
    setIsDeleting(false);
  };

  // cancel delete project
  const cancelDeleteProject = () => {
    setShowDeleteConfirm(false);
  };

  return (
    <div className="new-project-form">
      <div className="form-header">
        <button className="back-btn" onClick={handleBack}>
          ← Back
        </button>
        <h1>{isEditMode ? 'Edit Project' : 'Create New Project'}</h1>
      </div>

      {/* fetch status banner for edit mode */}
      {isEditMode && fetchBanner && (
        <div className={`info-banner ${fetchBanner.type}`} style={{ margin: '10px 0', padding: '8px 12px', borderRadius: '6px', fontSize: '13px' }}>
          {fetchBanner.type === 'error' ? '❌ ' : fetchBanner.type === 'notice' ? '⚠️ ' : '✅ '}
          {fetchBanner.message}
        </div>
      )}

      <form onSubmit={handleSubmit} className="project-form" noValidate>


        <div className="form-section">
          <h3>Project Details</h3>
          
          <div className="form-group">
            <label htmlFor="projectName">Project Name *</label>
            <input
              type="text"
              id="projectName"
              name="projectName"
              value={formData.projectName}
              onChange={handleInputChange}
              placeholder="Enter project name"
              required
              className={validationErrors.projectName ? 'error' : ''}
            />
            {validationErrors.projectName && (
              <div className="error-message">❌ {validationErrors.projectName}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="projectId">Project ID *</label>
            <input
              type="text"
              id="projectId"
              name="projectId"
              value={formData.projectId}
              onChange={handleInputChange}
              placeholder="e.g., P01, P02, P10"
              required
              pattern="^P\d{2}$"
              title="Project ID must be in format P followed by 2 digits (e.g., P01, P02, P10)"
              disabled={isEditMode}
              style={isEditMode ? { color: '#6c757d', fontStyle: 'italic' } : undefined}
              className={validationErrors.projectId ? 'error' : ''}
            />
            {validationErrors.projectId && (
              <div className="error-message">❌ {validationErrors.projectId}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="maxGroups">How many groups do you need for this project? *</label>
            <input
              type="number"
              id="maxGroups"
              name="maxGroups"
              value={formData.maxGroups}
              onChange={handleInputChange}
              placeholder="e.g., 10"
              min="1"
              required
              className={validationErrors.maxGroups ? 'error' : ''}
            />
            {validationErrors.maxGroups && (
              <div className="error-message">❌ {validationErrors.maxGroups}</div>
            )}
          </div>
          
          <div className="form-group">
            <label htmlFor="client">Client *</label>
            <input
              type="text"
              id="client"
              name="client"
              value={formData.client}
              onChange={handleInputChange}
              placeholder="e.g., SCS academic (academics from the School of Computer Science)"
              required
              className={validationErrors.client ? 'error' : ''}
            />
            {validationErrors.client && (
              <div className="error-message">❌ {validationErrors.client}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="description">Project Description *</label>
            <textarea
              id="description"
              name="description"
              value={formData.description}
              onChange={handleInputChange}
              placeholder="e.g., Project Description"
              rows={4}
              required
              className={validationErrors.description ? 'error' : ''}
            />
            {validationErrors.description && (
              <div className="error-message">❌ {validationErrors.description}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="deliverables">Expected Outcomes/Deliverables *</label>
            <textarea
              id="deliverables"
              name="deliverables"
              value={formData.deliverables}
              onChange={handleInputChange}
              placeholder="e.g., Expected Outcomes/Deliverables"
              rows={4}
              required
              className={validationErrors.deliverables ? 'error' : ''}
            />
            {validationErrors.deliverables && (
              <div className="error-message">❌ {validationErrors.deliverables}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="specificSkills">Specific Required Knowledge, Skills, and/or Technology *</label>
            <textarea
              id="specificSkills"
              name="specificSkills"
              value={formData.specificSkills}
              onChange={handleInputChange}
              placeholder="e.g., Web development experience. Javascript, python. Software Development"
              rows={3}
              required
              className={validationErrors.specificSkills ? 'error' : ''}
            />
            {validationErrors.specificSkills && (
              <div className="error-message">❌ {validationErrors.specificSkills}</div>
            )}
          </div>

          <div className="form-group">
            <label htmlFor="generalFields">Related General Fields/Disciplines *</label>
            {validationErrors.generalFields && (
              <div className="error-message">❌ {validationErrors.generalFields}</div>
            )}
            <div className="tags-container">
              <div className="available-tags">
                {availableTags.map(tag => (
                  <button
                    key={tag}
                    type="button"
                    className={`tag-btn ${selectedTags.includes(tag) ? 'selected' : ''}`}
                    onClick={() => handleTagToggle(tag)}
                  >
                    {tag}
                  </button>
                ))}
              </div>
            </div>
          </div>

          <div className="form-group">
            <label htmlFor="resourcesProvided">Resources Provided by the Client *</label>
            <textarea
              id="resourcesProvided"
              name="resourcesProvided"
              value={formData.resourcesProvided}
              onChange={handleInputChange}
              placeholder="introduction of fundamental knowledge, datasets, server"
              rows={3}
              required
              className={validationErrors.resourcesProvided ? 'error' : ''}
            />
            {validationErrors.resourcesProvided && (
              <div className="error-message">❌ {validationErrors.resourcesProvided}</div>
            )}
          </div>


        </div>



        <div className="form-actions">
          <button type="button" className="btn btn-secondary" onClick={handleDeleteProject}>
            {isEditMode ? '🗑️ Delete Project' : 'Cancel'}
          </button>
          <button type="submit" className="btn btn-primary" disabled={isSubmitting}>
            {isSubmitting ? 'Submitting...' : (isEditMode ? 'Update Project' : 'Create Project')}
          </button>
        </div>

        {/* time tracking display */}
        <div className="time-tracking" style={{ marginTop: '20px', padding: '10px', background: '#f8f9fa', borderRadius: '6px', fontSize: '12px', color: '#6c757d' }}>
          <strong>Time Tracking:</strong><br/>
          Start Time: {formData.startTime || 'Not set'}<br/>
          Finish Time: {formData.finishTime || 'Not set'}
        </div>
      </form>

      {/* delete project confirm modal */}
      {showDeleteConfirm && (
        <DeleteConfirmModal
          isOpen={showDeleteConfirm}
          onClose={cancelDeleteProject}
          onConfirm={confirmDeleteProject}
          projectName={formData.projectName || 'Untitled Project'}
          projectId={formData.projectId || 'Unknown'}
          isDeleting={isDeleting}
        />
      )}

      {/* delete error modal */}
      {showDeleteErrorModal && (
        <div className="modal-overlay">
          <div className="modal-content">
            <div className="modal-header">
              <h3>❌ Delete Failed</h3>
            </div>
            <div className="modal-body">
              <p>{deleteErrorMessage}</p>
              <p><strong>Local data has been preserved.</strong></p>
            </div>
            <div className="modal-actions">
              <button className="btn btn-primary" onClick={() => setShowDeleteErrorModal(false)}>
                OK
              </button>
            </div>
          </div>
        </div>
      )}

      {/* success message modal */}
      {showSuccessMessage && (
        <div className="modal-overlay">
          <div className="modal-content success-modal">
            <div className="modal-header">
              <h3>{successMessage.includes('HTTP') || successMessage.includes('Error') || successMessage.includes('Failed') ? '❌ Error' : '✅ Success'}</h3>
            </div>
            <div className="modal-body">
              <p>{successMessage}</p>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

export default NewProjectForm;
